PREAMBLE_PATTERN = re.compile(
    r"^(?:okay|sure|here'?s|here is|certainly|absolutely)"
    r"(?:[,:!.\s-].*)?$",
    re.IGNORECASE,
)


def _clean(text, hashtags):
    """
    Clean generated content and append unique hashtags.
    """

    if not isinstance(text, str):
        raise ValueError("Generated content must be a string.")

    # Remove hashtags generated by the language model.
    text = re.sub(
        r"(?<!\w)#[A-Za-z0-9_]+",
        "",
        text
    )

    # Remove empty lines and unnecessary introductions.
    lines = [
        line.strip()
        for line in text.strip().splitlines()
    ]

    while lines and (
        not lines[0]
        or PREAMBLE_PATTERN.match(lines[0])
    ):
        lines.pop(0)

    text = "\n".join(lines)

    # Remove excessive spaces without destroying paragraph spacing.
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)

    text = text.strip()

    # Normalize supplied hashtags.
    if hashtags:

        if isinstance(hashtags, str):
            hashtag_list = hashtags.split()

        elif isinstance(hashtags, (list, tuple, set)):
            hashtag_list = hashtags

        else:
            raise ValueError(
                "Hashtags must be a string, list, tuple or set."
            )

        clean_hashtags = []
        seen_hashtags = set()

        for hashtag in hashtag_list:

            hashtag = str(hashtag).strip().lstrip("#")

            hashtag = re.sub(
                r"[^\w]",
                "",
                hashtag,
                flags=re.UNICODE
            )

            if not hashtag:
                continue

            hashtag_key = hashtag.lower()

            if hashtag_key not in seen_hashtags:
                clean_hashtags.append("#" + hashtag)
                seen_hashtags.add(hashtag_key)

        if clean_hashtags:
            text += "\n\n" + " ".join(clean_hashtags)

    return text


def generate_content(
    topic,
    platform,
    tone,
    output_type,
    trends,
    hashtags,
    best_angle=None,
    feedback=None,
    previous_draft=None,
):
    """
    Generate high-quality platform-specific social media content.

    Supports:
    - Topic-specific content generation
    - Research context
    - Reviewer feedback
    - Draft revision
    - Hashtag integration
    """

    # 1. Validate input.
    if not topic or not str(topic).strip():
        raise ValueError("Topic cannot be empty.")

    topic = str(topic).strip()

    if not platform:
        raise ValueError("Platform cannot be empty.")

    if not tone:
        raise ValueError("Tone cannot be empty.")

    # 2. Prepare research context.
    if isinstance(trends, str):
        trend_list = [trends] if trends.strip() else []

    elif isinstance(trends, (list, tuple)):
        trend_list = [
            str(item).strip()
            for item in trends
            if item and str(item).strip()
        ]

    else:
        trend_list = []

    research_context = "\n".join(
        f"- {item}" for item in trend_list
    ) if trend_list else "No additional research available."

    angle = str(best_angle).strip() if best_angle else topic

    # 3. Get platform instructions.
    platform_rules = PLATFORM_INSTRUCTIONS.get(
        platform,
        """
- Write clear, informative and engaging content.
- Use short paragraphs.
- Start with a strong hook.
- Include meaningful information.
- End with a relevant CTA.
"""
    )

    # 4. Prepare revision instructions.
    revision_block = ""

    if feedback and previous_draft:

        revision_block = f"""
REVISION MODE: ENABLED

PREVIOUS DRAFT:
{previous_draft}

REVIEWER FEEDBACK:
{feedback}

YOUR REVISION TASK:

1. Carefully understand every reviewer complaint.
2. Fix the most important weaknesses first.
3. Replace generic sentences with specific information.
4. Improve the hook if it is weak.
5. Remove repetition and unnecessary wording.
6. Improve transitions between paragraphs.
7. Preserve the useful information from the original draft.
8. Do not introduce new unsupported facts.
9. Do not simply change a few words.
10. Return a genuinely improved complete caption.

The new version must address the reviewer's feedback.
"""

    # 5. Build the improved generation prompt.
    prompt = f"""
You are TrendPilot, a professional social media content strategist
and experienced copywriter.

Your responsibility is to create content that people genuinely
want to read, understand, engage with and share.

Do not write like a generic AI assistant.

==============================
CONTENT BRIEF
==============================

Topic: {topic}

Platform: {platform}

Writing Tone: {tone}

Selected Output: {output_type}

Selected Content Angle: {angle}

==============================
RESEARCH CONTEXT
==============================

{research_context}

IMPORTANT:
- Use research context when it provides relevant information.
- Distinguish research findings from opinions and predictions.
- Do not treat an unverified trend or rumor as established fact.
- Never invent statistics, dates, announcements or quotations.
- If reliable details are unavailable, use thoughtful commentary
  instead of pretending to know specific facts.

==============================
PLATFORM WRITING STRATEGY
==============================

{platform_rules}

==============================
CONTENT CREATION RULES
==============================

1. HOOK QUALITY

The first sentence must immediately give readers a reason to continue.

Use approaches such as:
- An interesting observation.
- A surprising but supported detail.
- A relatable situation.
- A thought-provoking question.
- A specific benefit or insight.

Avoid generic openings such as:
"Get ready to lose your minds!"
"The world is changing!"
"Something amazing is happening!"

Do not use the same hook formula for every topic.

2. TOPIC UNDERSTANDING

Understand the actual subject before writing.

Name the requested topic explicitly and naturally in the first
two sentences. Do not rely on adjacent examples alone to signal relevance.

Every paragraph must contribute something meaningful to the topic.

Do not simply repeat the topic using different words.

Avoid unrelated references, incorrect terminology and misleading
comparisons.

3. INFORMATION VALUE

Give the reader a clear, topic-specific takeaway. A caption should
teach, explain, compare or help the audience decide or act; merely
naming the topic or praising it does not count as useful information.

Prefer:
- One concrete example, mechanism, trade-off or practical step.
- A brief explanation of why the detail matters to this audience.
- A useful comparison or implication when it clarifies the topic.
- A next step readers can apply, when appropriate.

Use enough detail to make the takeaway understandable, while keeping
the caption concise. Support factual details with the prompt or reliable
context; never invent numbers, named sources or product claims. If a
specific fact is unavailable, use a clearly framed general explanation
or ask a focused question instead of padding with generic praise.

4. ORIGINALITY

Avoid overused AI expressions, including:
- "In today's fast-paced world"
- "The future is here"
- "It's not just about..."
- "Game changer"
- "Take things to the next level"
- "Let's dive in"

These expressions are not absolutely forbidden, but use them
only when they genuinely fit.

Avoid repetitive sentence structures.

5. NATURAL FLOW

Structure the caption naturally:

Opening: Capture attention.

Body: Explain the topic and provide meaningful value.

Ending: Leave the reader with a thought, question or action.

Make transitions smooth.

Do not make the caption sound like a rigid essay.

6. AUDIENCE ENGAGEMENT

Understand what the intended platform audience might care about.

Use one relevant CTA or question.

Avoid generic endings such as:
"Let us know your thoughts!"
"Comment below!"

unless the question itself makes the interaction meaningful.

7. TONE CONTROL

Maintain the selected tone throughout the caption.

Professional means insightful, not unnecessarily complicated.

Funny means genuinely witty, not random jokes.

Motivational means inspiring, not empty motivational phrases.

Casual means conversational, not careless.

Exciting means energetic, not exaggerated.

8. FACTUAL RESPONSIBILITY

Never fabricate:
- Statistics.
- Research findings.
- Official announcements.
- Product features.
- Release information.
- Personal experiences.

Do not present rumors as confirmed facts.

9. HASHTAG CONTROL

Do not generate hashtags.

TrendPilot will append its separately generated hashtags.

10. OUTPUT REQUIREMENTS

Return only the finished social-media post/caption, regardless of the
selected output type. The reel/video script is generated separately by
another tool; never include a script, title or thumbnail in this response.

Do not include:
- Your explanation.
- Your analysis.
- A quality score.
- An introduction.
- Unrequested headings.

==============================
FINAL QUALITY CHECK
==============================

Before returning the caption, internally check:

- Is the hook interesting and specific?
- Does the body deliver at least one concrete, accurate topic-specific
  takeaway and explain why it matters?
- Could a reader summarize what they learned or what to do next?
- Is the caption genuinely about the requested topic?
- Does every paragraph add value?
- Are the claims supported?
- Does the writing sound natural?
- Is the content appropriate for the selected platform?
- Is the ending meaningful?
- Is there unnecessary repetition?

If the answer to any question is no, improve the draft
before returning it.

{revision_block}

Now create the best possible {output_type} for {platform}.

Remember: Quality, relevance and usefulness matter more than
sounding impressive.
"""

    # 6. Generate using Ollama.
    response = generate_response(
        prompt,
        temperature=0.65
    )

    # 7. Validate response.
    if not isinstance(response, str) or not response.strip():
        raise ValueError(
            "The model returned empty or invalid content."
        )

    # 8. Clean and append hashtags.
    final_content = _clean(
        response,
        hashtags
    )

    if not final_content.strip():
        raise ValueError(
            "No usable content was generated."
        )

    return final_content
    
